"""Create+verify an immutable local v210 checkpoint; preserve all v209 refs."""
from pathlib import Path
import importlib.util,json,subprocess
r=Path(__file__).resolve().parents[1];label='a733-v210-voice-recovery-r6-20261030'
assert subprocess.check_output(['git','status','--porcelain'],cwd=r)==b'','commit all source/evidence first'
old=r/'out/checkpoints/a733-v209-affinity-async-recovery-20261029/manifest.json'
references=[Path(x['path']) for x in json.loads(old.read_text())['references']]
references += [r.parent/'openvela-a733-cubie-a7z-sd-v210-voice-latency-candidate.img',
               r.parent/'openvela-a733-cubie-a7z-sd-v210-voice-latency-candidate.img.sha256']
references += list((r/'out/v210-release-20261030').iterdir())
for name in ('asr-real-r2-report.tar.gz','layout-qualified-r3-report.tar.gz'):
    references.append(r/'out/asr-native-v183-r1'/name)
for directory in ('general-voice-assets-v185-r2','general-asr-export-v184-r2',
                  'ort-capi-host-v184-r1','matcha-ort-v183-r1','acoustic-capi-host-v184-r2',
                  'a733-kws-wav-v161-r2','a733-openvela-kws-v158-r2','voice-board-checks-v190-r1',
                  'a733-linux-general-asr-v183-r1','imx214-mode-v187-r1'):
    # WSL soname symlink uses an LX reparse tag that native Windows Python
    # cannot stat (WinError 1920). Preserve the real versioned ELF + wheel;
    # the alias is regenerated by the existing host test, not a data payload.
    references.extend(f for f in (r/'out'/directory).rglob('*')
                      if f.name!='libonnxruntime.so.1' and not f.is_symlink() and f.is_file() and f.stat().st_size)
references.extend(f for f in (r.parent/'references/matcha-icefall-zh-baker').rglob('*')
                  if f.is_file() and not f.is_symlink() and f.stat().st_size)
unique={str(f.resolve(strict=True)):f.resolve(strict=True) for f in references}
# Calling the existing implementation directly avoids Windows CreateProcess
# 32K command-line limits when hundreds of long reference paths are supplied.
spec=importlib.util.spec_from_file_location('checkpoint',r/'tools/checkpoint-a733-project.py')
checkpoint=importlib.util.module_from_spec(spec);spec.loader.exec_module(checkpoint)
print(json.dumps(checkpoint.create(r,label,list(unique.values())),indent=2))
checkpoint.verify(r/'out/checkpoints'/label,True)
print('V210_CHECKPOINT_AND_ALL_EXTERNAL_REFERENCE_HASHES_VERIFIED',len(unique))
