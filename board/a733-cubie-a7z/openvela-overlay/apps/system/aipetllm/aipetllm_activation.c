void aipetllm_swiglu(size_t n,float *out,const float *gate,const float *up)
{
  size_t i=0;
#if defined(__ARM_NEON) && defined(__aarch64__)
  for(;i+3<n;i+=4)vst1q_f32(out+i,vmulq_f32(ggml_v_silu(vld1q_f32(gate+i)),vld1q_f32(up+i)));
#elif defined(__SSE2__)
  for(;i+3<n;i+=4)_mm_storeu_ps(out+i,_mm_mul_ps(ggml_v_silu(_mm_loadu_ps(gate+i)),_mm_loadu_ps(up+i)));
#endif
  for(;i<n;++i)out[i]=(gate[i]/(1.0f+expf(-gate[i])))*up[i];
}

/* GGML's KV attention softmax has padded (masked -infinity) rows. Evaluate
 * the last four-lane group with masked zeros too, rather than switching its
 * valid tail to a different expf approximation. Never write past n. */
double aipetllm_softmax_exp(size_t n,float *out,const float *in,float maximum)
{
  double total=0;
  for(size_t i=0;i<n;i+=4) {
    float x[4]={-INFINITY,-INFINITY,-INFINITY,-INFINITY},y[4];
    size_t count=n-i<4?n-i:4;
    for(size_t j=0;j<count;++j)x[j]=in[i+j];
#if defined(__ARM_NEON) && defined(__aarch64__)
    float32x4_t v=ggml_v_expf(vsubq_f32(vld1q_f32(x),vdupq_n_f32(maximum)));
    vst1q_f32(y,v);total+=(double)vaddvq_f32(v);
#elif defined(__SSE2__)
    __m128 v=ggml_v_expf(_mm_sub_ps(_mm_loadu_ps(x),_mm_set1_ps(maximum)));
    _mm_storeu_ps(y,v);
    __m128 t=_mm_shuffle_ps(v,v,_MM_SHUFFLE(2,3,0,1));
    v=_mm_add_ps(v,t);t=_mm_movehl_ps(t,v);v=_mm_add_ss(v,t);
    total+=(double)_mm_cvtss_f32(v);
#else
    for(size_t j=0;j<4;++j)y[j]=expf(x[j]-maximum);
    total+=(double)y[0]+y[1]+y[2]+y[3];
#endif
    for(size_t j=0;j<count;++j)out[i+j]=y[j];
  }
  return total;
}

